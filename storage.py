"""Общее место хранения данных бота.

Все таблицы лежат в одном файле SQLite, и подключение к нему собрано здесь:
раньше каждый репозиторий открывал соединение сам, и настройки приходилось
бы менять в трёх местах.

Имя `rejections.db` осталось с тех пор, когда в базе были только отклонённые
вакансии. Сейчас там ещё профили, выбранные направления, действия по
вакансиям и сами вакансии. Переименование — отдельная задача: оно требует
переноса живых данных.
"""

import sqlite3


DATABASE_PATH = "data/rejections.db"

# Сколько ждать, если база занята другим запросом. С одним пользователем
# записи не пересекались никогда, а с несколькими — будут.
BUSY_TIMEOUT_SECONDS = 5


def connect(database_path):
    """Открывает соединение, готовое к одновременной работе нескольких людей.

    WAL позволяет читать во время записи: без него пишущий запрос блокирует
    всех остальных, и они получают `database is locked`. Таймаут задаёт,
    сколько ждать освобождения, прежде чем сдаться с ошибкой.
    """

    connection = sqlite3.connect(
        database_path,
        isolation_level=None,
        timeout=BUSY_TIMEOUT_SECONDS,
    )
    connection.execute("PRAGMA journal_mode = WAL")
    connection.execute(
        "PRAGMA busy_timeout = %d" % (BUSY_TIMEOUT_SECONDS * 1000)
    )
    return connection
