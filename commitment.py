"""Формат работы: разовая задача или постоянное сотрудничество.

Определяется по словам в тексте вакансии. Списки ниже можно свободно
редактировать — формат тот же, что у направлений: звёздочка на конце
означает «и любое окончание».

Важно понимать ограничение: большинство объявлений про длительность прямо
не пишут. Для них формат остаётся неизвестным (`None`), и такие вакансии
показываются как обычно — прятать их нельзя, иначе выдача схлопнется.
"""

import re

from keywords import compile_keywords, has_match


ONE_OFF = "one_off"
ONGOING = "ongoing"

# Значение в профиле, когда формат работы неважен.
ANY = "any"

COMMITMENTS = (ONE_OFF, ONGOING)

NAMES = {
    ONE_OFF: "разовая задача",
    ONGOING: "постоянное сотрудничество",
}

LABELS = {
    ONE_OFF: "⚡ Разовая",
    ONGOING: "🔁 Долгосрок",
}


# Постоянное сотрудничество: работа, которая не заканчивается одним макетом.
ONGOING_KEYWORDS = (
    "на постоянной основе", "постоянн* основе", "постоянн* сотрудничеств*",
    "долгосрочн*", "долгосрок*", "постоянн* поток*", "регулярн* задач*",
    "в штат", "в команду на постоянн*", "штатн*",
    "ежемесячн*", "в месяц", "оклад", "ставка в месяц",
    "часов в неделю", "часа в неделю", "в неделю", "загрузк*",
    "испытательн* срок", "график работы", "полн* занятост*",
    "частичн* занятост*", "на длительн*",
)

# Разовая задача: один понятный результат и конец.
ONE_OFF_KEYWORDS = (
    "разов*", "один макет", "одна карточка", "одну карточку",
    "одна презентация", "одну презентацию", "единоразов*",
    "к завтра", "до завтра", "до конца дня", "в течение дня",
    "за один день", "на один день",
    "нужно сделать один", "закрыть одну задачу", "точечн* задач*",
)

# Явное количество работы («20 слайдов», «10 карточек») — признак того, что
# объём конечен. Сигнал слабее прямых слов, поэтому проверяется последним.
QUANTITY_PATTERN = re.compile(
    r"\b\d{1,3}\s*(?:слайд\w*|карточ\w*|баннер\w*|макет\w*|обложк\w*"
    r"|афиш\w*|постер\w*|креатив\w*|иллюстрац\w*|модел\w*|ролик\w*)",
    re.IGNORECASE,
)


_ONGOING_PATTERNS = compile_keywords(ONGOING_KEYWORDS)
_ONE_OFF_PATTERNS = compile_keywords(ONE_OFF_KEYWORDS)


def detect_commitment(text):
    """Возвращает формат работы или None, если по тексту не понять.

    Порядок проверок задаёт приоритет. Прямое указание на постоянную работу
    перевешивает всё: «нужно 20 слайдов, работа на постоянной основе» — это
    долгосрок, хотя объём назван. Явное указание на разовость идёт следом,
    и только потом — слабый признак в виде количества работ.
    """

    if has_match(text, _ONGOING_PATTERNS):
        return ONGOING

    if has_match(text, _ONE_OFF_PATTERNS):
        return ONE_OFF

    if QUANTITY_PATTERN.search(text):
        return ONE_OFF

    return None


def commitment_name(value):
    return NAMES.get(value, "не определён")


def commitment_label(value):
    """Короткая метка для карточки вакансии или None."""

    return LABELS.get(value)
