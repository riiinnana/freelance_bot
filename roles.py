"""Кого ищут в вакансии: дизайнера или кого-то другого.

На живых тестах в выдачу полезли SMM-менеджеры, маркетологи и сценаристы.
Проходили они честно: направления вроде «Рекламные креативы» и «Рилсы»
опознаются по словам `креатив*`, `reels`, `tiktok`, `публикаци*` — а такие
слова есть в любой вакансии эсэмэмщика. Слово названо, а работа не та.

Отличает их не тема, а роль в заголовке. «SMM-менеджер: вести аккаунт,
писать тексты, публиковать по контент-плану» — тема дизайнерская, роль
чужая. Поэтому здесь два списка ролей, и решение принимается по заголовку,
а не по всему тексту: в теле «дизайн» и «smm» встречаются вперемешку, а в
заголовке стоит именно то, кого зовут.

Названа обе роли сразу — вакансия остаётся: «SMM-дизайнер» и «дизайнер
креативов для таргета» это работа руками дизайнера, как её ни назови.
"""

